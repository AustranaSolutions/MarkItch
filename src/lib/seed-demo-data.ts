function pickRandom<T>(pool: T[], n: number): T[] {
  const copy = [...pool];
  const out: T[] = [];
  for (let i = 0; i < n && copy.length > 0; i++) {
    const idx = Math.floor(Math.random() * copy.length);
    out.push(copy.splice(idx, 1)[0]);
  }
  return out;
}

export type SeedDemoResult = { brands: number; battles: number; viewers: number };

export async function seedDemoContent(db: Db): Promise<SeedDemoResult> {
  // Wipe previous demo data first — namespaced, so this only ever touches
  // rows this same function created.
  const slugs = BRANDS.map((b) => b.slug);
  await db.delete(brands).where(inArray(brands.slug, slugs)); // cascades battles/votes/comments/likes/challenges
  await db
    .delete(users)
    .where(or(like(users.email, `%@${DEMO_EMAIL_DOMAIN}`), like(users.email, `%@${LEGACY_DEMO_EMAIL_DOMAIN}`))); // cascades brandMembers/follows/etc left over

  const passwordHash = await bcrypt.hash(DEMO_PASSWORD, 12);

  const viewerRows = await db
    .insert(users)
    .values(
      Array.from({ length: VIEWER_COUNT }, (_, i) => ({
        email: `demo-viewer-${i + 1}@${DEMO_EMAIL_DOMAIN}`,
        passwordHash,
        name: `Demo Viewer ${i + 1}`,
        accountType: "assent" as const,
        emailVerifiedAt: new Date(),
      })),
    )
    .returning({ id: users.id });
  const viewerIds = viewerRows.map((r) => r.id);

  const brandIdBySlug = new Map<string, string>();
  for (const b of BRANDS) {
    const [owner] = await db
      .insert(users)
      .values({
        email: `demo-owner-${b.slug}@${DEMO_EMAIL_DOMAIN}`,
        passwordHash,
        name: `${b.name} Team`,
        accountType: "acro",
        emailVerifiedAt: new Date(),
      })
      .returning({ id: users.id });

    const [brand] = await db
      .insert(brands)
      .values({
        name: b.name,
        slug: b.slug,
        description: b.description,
        website: `https://${b.slug}.example`,
        category: b.category,
        country: b.country,
      })
      .returning({ id: brands.id });

    await db.insert(brandMembers).values({ brandId: brand.id, userId: owner.id, role: "owner" });
    brandIdBySlug.set(b.slug, brand.id);

    const upsetWinners = new Set(["sprintex", "voltrix", "glowbotanic"]);
    const followerCount = b.isGoliath ? 25 + Math.floor(Math.random() * 20) : upsetWinners.has(b.slug) ? 10 + Math.floor(Math.random() * 8) : 4 + Math.floor(Math.random() * 6);
    const followers = pickRandom(viewerIds, followerCount);
    if (followers.length > 0) {
      await db.insert(follows).values(followers.map((userId) => ({ userId, brandId: brand.id })));
    }
  }

  for (const seed of BATTLE_SEEDS) {
    const brandAId = brandIdBySlug.get(seed.aSlug)!;
    const brandBId = brandIdBySlug.get(seed.bSlug)!;

    const hasVideoA = seed.stage === "finished" || seed.stage === "live" || (seed.stage === "awaiting_one" && seed.missingSide !== "a");
    const hasVideoB = seed.stage === "finished" || seed.stage === "live" || (seed.stage === "awaiting_one" && seed.missingSide !== "b");

    const productionDeadline =
      seed.stage === "awaiting_both" || seed.stage === "awaiting_one" ? daysFromNow(seed.productionDays ?? 10) : null;
    const votingEndsAt =
      seed.stage === "finished"
        ? daysAgo(seed.votingEndedDaysAgo ?? 5)
        : seed.stage === "live"
          ? daysFromNow(seed.votingEndsInDays ?? 3)
          : null;

    const [battle] = await db
      .insert(battles)
      .values({
        brandAId,
        brandBId,
        mode: seed.mode,
        category: seed.category,
        brandAVideoUrl: hasVideoA ? videoUrl(seed.aSlug) : null,
        brandBVideoUrl: hasVideoB ? videoUrl(seed.bSlug) : null,
        brandASubmittedAt: hasVideoA ? daysAgo(seed.createdDaysAgo) : null,
        brandBSubmittedAt: hasVideoB ? daysAgo(seed.createdDaysAgo) : null,
        productionDeadline,
        votingEndsAt,
        createdAt: daysAgo(seed.createdDaysAgo),
      })
      .returning({ id: battles.id });

    if (!seed.totalVotes) continue;

    // Votes need a createdAt inside the battle's own simulated timeline
    // (between it going live and votingEndsAt) — not "now", or
    // getVoteTallyAsOf (the frozen official result, used by the feed and
    // by /battles/[id]'s share card) would filter every one of them out
    // for a "finished" battle, since votingEndsAt is in the simulated
    // past.
    const voteWindowStartMs = daysAgo(seed.createdDaysAgo).getTime();
    const voteWindowEndMs = Math.min(votingEndsAt ? votingEndsAt.getTime() : Date.now(), Date.now());
    const randomVoteDate = () => new Date(voteWindowStartMs + Math.random() * Math.max(1, voteWindowEndMs - voteWindowStartMs));

    const total = seed.totalVotes;
    const aVotes = Math.round(total * (seed.aShare ?? 0.5));
    const bVotes = total - aVotes;
    const voters = pickRandom(viewerIds, total);
    const aVoters = voters.slice(0, aVotes);
    const bVoters = voters.slice(aVotes);

    if (aVoters.length > 0) {
      await db
        .insert(votes)
        .values(aVoters.map((userId) => ({ battleId: battle.id, userId, votedForBrandId: brandAId, createdAt: randomVoteDate() })));
    }
    if (bVoters.length > 0) {
      await db
        .insert(votes)
        .values(bVoters.map((userId) => ({ battleId: battle.id, userId, votedForBrandId: brandBId, createdAt: randomVoteDate() })));
    }

    const aLikers = pickRandom(viewerIds, Math.round(aVotes * 0.6));
    const bLikers = pickRandom(viewerIds, Math.round(bVotes * 0.6));
    if (aLikers.length > 0) await db.insert(likes).values(aLikers.map((userId) => ({ battleId: battle.id, brandId: brandAId, userId })));
    if (bLikers.length > 0) await db.insert(likes).values(bLikers.map((userId) => ({ battleId: battle.id, brandId: brandBId, userId })));

    const commenters = pickRandom(viewerIds, 2 + Math.floor(Math.random() * 4));
    const commentTexts = pickRandom(COMMENT_POOL, commenters.length);
    if (commenters.length > 0) {
      await db.insert(comments).values(
        commenters.map((userId, i) => ({
          battleId: battle.id,
          userId,
          content: commentTexts[i],
          createdAt: daysAgo(Math.random() * (seed.createdDaysAgo / 2)),
        })),
      );
    }
  }

  // Phase 13: solo pitches, reactions, and a pending "Pitch schicken" —
  // reuses each brand's own demo video asset rather than generating new
  // clips per reaction.
  const soloPitchIdBySlug = new Map<string, string>();
  for (const seed of SOLO_PITCH_SEEDS) {
    const brandId = brandIdBySlug.get(seed.brandSlug)!;
    const [pitch] = await db
      .insert(soloPitches)
      .values({
        brandId,
        videoUrl: videoUrl(seed.brandSlug),
        category: DEFAULT_CATEGORY,
        createdAt: daysAgo(seed.createdDaysAgo),
      })
      .returning({ id: soloPitches.id });
    soloPitchIdBySlug.set(seed.brandSlug, pitch.id);

    const likers = pickRandom(viewerIds, 8 + Math.floor(Math.random() * 12));
    if (likers.length > 0) {
      await db.insert(likes).values(likers.map((userId) => ({ soloPitchId: pitch.id, brandId, userId })));
    }
    const commenters = pickRandom(viewerIds, 1 + Math.floor(Math.random() * 3));
    const commentTexts = pickRandom(COMMENT_POOL, commenters.length);
    if (commenters.length > 0) {
      await db.insert(comments).values(
        commenters.map((userId, i) => ({ soloPitchId: pitch.id, userId, content: commentTexts[i] })),
      );
    }
  }

  const reactionIdByKey = new Map<string, string>();
  for (const seed of REACTION_SEEDS) {
    const soloPitchId = soloPitchIdBySlug.get(seed.soloPitchBrandSlug);
    const reactorBrandId = brandIdBySlug.get(seed.reactorSlug);
    if (!soloPitchId || !reactorBrandId) continue;
    const parentReactionId = seed.replyTo ? (reactionIdByKey.get(seed.replyTo) ?? null) : null;

    const [reaction] = await db
      .insert(reactions)
      .values({
        soloPitchId,
        brandId: reactorBrandId,
        parentReactionId,
        videoUrl: videoUrl(seed.reactorSlug),
        createdAt: daysAgo(seed.createdDaysAgo),
      })
      .returning({ id: reactions.id });
    if (seed.key) reactionIdByKey.set(seed.key, reaction.id);

    // The promoted reaction gets more likes than the other(s) on the same
    // pitch, so "sortiert nach Likes" visibly picks it as the best answer.
    const likerCount = seed.promote ? 30 + Math.floor(Math.random() * 10) : 5 + Math.floor(Math.random() * 8);
    const likers = pickRandom(viewerIds, likerCount);
    if (likers.length > 0) {
      await db.insert(likes).values(likers.map((userId) => ({ reactionId: reaction.id, brandId: reactorBrandId, userId })));
    }

    if (seed.promote) {
      const pitchBrandId = brandIdBySlug.get(seed.soloPitchBrandSlug)!;
      const [promotedBattle] = await db
        .insert(battles)
        .values({
          brandAId: pitchBrandId,
          brandBId: reactorBrandId,
          mode: "open",
          category: DEFAULT_CATEGORY,
          brandAVideoUrl: videoUrl(seed.soloPitchBrandSlug),
          brandASubmittedAt: daysAgo(SOLO_PITCH_SEEDS.find((s) => s.brandSlug === seed.soloPitchBrandSlug)!.createdDaysAgo),
          brandBVideoUrl: videoUrl(seed.reactorSlug),
          brandBSubmittedAt: daysAgo(seed.createdDaysAgo),
          votingEndsAt: daysFromNow(4),
        })
        .returning({ id: battles.id });
      await db.update(reactions).set({ promotedToBattleId: promotedBattle.id }).where(inArray(reactions.id, [reaction.id]));

      const voters = pickRandom(viewerIds, 40);
      if (voters.length > 0) {
        await db.insert(votes).values(
          voters.map((userId, i) => ({
            battleId: promotedBattle.id,
            userId,
            votedForBrandId: i % 2 === 0 ? pitchBrandId : reactorBrandId,
          })),
        );
      }
    }
  }

  const pendingChallengePitchId = soloPitchIdBySlug.get(PENDING_PITCH_CHALLENGE.soloPitchBrandSlug);
  const pendingChallengerBrandId = brandIdBySlug.get(PENDING_PITCH_CHALLENGE.challengerSlug);
  const pendingChallengedBrandId = brandIdBySlug.get(PENDING_PITCH_CHALLENGE.soloPitchBrandSlug);
  if (pendingChallengePitchId && pendingChallengerBrandId && pendingChallengedBrandId) {
    await db.insert(challenges).values({
      challengerBrandId: pendingChallengerBrandId,
      challengedBrandId: pendingChallengedBrandId,
      soloPitchId: pendingChallengePitchId,
      status: "pending",
      expiresAt: daysFromNow(14),
    });
  }

  return { brands: BRANDS.length, battles: BATTLE_SEEDS.length, viewers: VIEWER_COUNT };
}

// Re-running wipes and recreates only rows tied to those namespaces.
//
// Videos are static files under public/demo/videos/ (generated by
// scripts/generate-demo-videos.sh, already committed) — served by Next.js
// like any other static asset, no Supabase Storage credentials needed.
//
// This is the shared implementation used by both:
//   - src/db/seed-demo.ts (npm run db:seed-demo — a local/CLI connection)
//   - src/app/api/admin/seed-demo/route.ts (a browser-visitable endpoint
//     that runs against whatever DATABASE_URL the deployment already has —
//     so seeding prod never requires a terminal or a copy-pasted connection
//     string).
// Takes a `db` instance rather than opening its own connection, so each
// caller manages its own connection lifecycle.

